"""
Regenerate frontend/src/data/defaultCatalog.ts (the offline fallback catalog)
from backend/apps/catalog/catalog_data.py so both always match.

    python backend/scripts/export_catalog.py
"""
import importlib.util
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('catalog_data', ROOT / 'backend/apps/catalog/catalog_data.py')
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)

occasions = []
for o in mod.CATALOG:
    occasions.append({
        'id': o['id'],
        'slug': o['slug'],
        'display_name': o['name'],
        'description': o['desc'],
        'icon_name': o['icon'],
        'packages': [
            {
                'id': p['id'],
                'occasion': o['id'],
                'code': p['code'],
                'name': p['name'],
                'base_price_inr': f"{p['price']}.00",
                'features_json': p['features'],
                'included_revisions': p['revisions'],
                'is_active': True,
            }
            for p in o['packages']
        ],
    })

out = ROOT / 'frontend/src/data/defaultCatalog.ts'
out.write_text(
    "// GENERATED by backend/scripts/export_catalog.py from backend/apps/catalog/catalog_data.py.\n"
    "// Do not edit by hand. Used only when the catalog API is unreachable.\n"
    "import { Occasion, Addon } from '../types';\n\n"
    f"export const OFFICIAL_OCCASIONS: Occasion[] = {json.dumps(occasions, ensure_ascii=False, indent=2)};\n\n"
    "/** Paid add-ons are retired: every package is a flat ₹399 / ₹499 / ₹599 price. */\n"
    "export const OFFICIAL_ADDONS: Addon[] = [];\n",
    encoding='utf-8',
)
print(f"Wrote {out.relative_to(ROOT)}: {len(occasions)} occasions, "
      f"{sum(len(o['packages']) for o in occasions)} packages")
